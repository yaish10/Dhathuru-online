  function normalizeTicket(t) {
    t = t || {};
    var seats = Array.isArray(t.seats) ? t.seats : (t.seats ? String(t.seats).split(/[ ,]+/) : []);
    seats = seats.filter(Boolean);
    var pax = t.passengers != null ? Number(t.passengers) : seats.length;
    return {
      reference: t.reference || "", from: t.from || "", to: t.to || "", date: t.date || "", time: t.time || "", vessel: t.vessel || "",
      seats: seats, seatsText: seats.join(", "), seatsBooked: t.seatsBooked != null ? Number(t.seatsBooked) : (pax || seats.length),
      customerName: t.customerName || "", customerPhone: t.customerPhone || "", passengers: pax || 0,
      paymentStatus: t.paymentStatus || "Unpaid", paid: /^paid$/i.test(t.paymentStatus || "")
    };
  }
