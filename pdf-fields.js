  function forType(docType) {
    return ALL.filter(function (f) {
      return f.docs.indexOf("*") >= 0 || f.docs.indexOf(docType) >= 0;
    });
  }

  function getPath(obj, path) {
    if (!obj || !path) return undefined;
    var parts = String(path).split(".");
    var cur = obj;
    for (var i = 0; i < parts.length; i++) {
      if (cur == null || typeof cur !== "object") return undefined;
      if (!Object.prototype.hasOwnProperty.call(cur, parts[i])) return undefined;
      cur = cur[parts[i]];
    }
    return cur;
  }

  function money(n, currency) {
    var x = Number(n);
    if (!isFinite(x)) return "—";
    return (currency || "MVR") + " " + x.toLocaleString("en-GB", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  function format(value, type, currency) {
    if (value == null || value === "") return "";
    if (type === "money") return money(value, currency);
    if (type === "number") return Number(value).toLocaleString("en-GB");
    if (type === "date") {
      try { return new Date(value).toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" }); }
      catch (e) { return String(value); }
    }
    if (type === "datetime") {
      try { return new Date(value).toLocaleString("en-GB"); }
      catch (e) { return String(value); }
    }
    if (type === "table" || typeof value === "object") return "";
    return String(value);
  }

  /** Build document data bag from company row + source record. Company always from DB. */
  function buildData(docType, company, source, opts) {
    opts = opts || {};
    var logoUrl = "";
    if (company && company.logo_path && window.veyoraDb) {
      try {
        logoUrl = window.veyoraDb.storage.from("company-logos").getPublicUrl(company.logo_path).data.publicUrl || "";
        if (logoUrl) logoUrl += (logoUrl.indexOf("?") >= 0 ? "&" : "?") + "t=" + Date.now();
      } catch (e) { logoUrl = ""; }
    }
    var currency = (company && company.currency) || "MVR";
    var base = {
      company: {
        name: (company && company.name) || "",
        logoUrl: logoUrl,
        address: (company && company.address) || "",
        phone: (company && company.phone) || "",
        email: (company && company.email) || "",
        registrationNo: (company && company.registration_no) || "",
        region: (company && company.region) || "",
        currency: currency
      },
      _sample: !!opts.sample,
      _currency: currency
    };

    if (docType === "invoice") {
      var inv = source || sampleInvoice(currency);
      base.invoice = {
        number: inv.code || inv.number || "INV-SAMPLE",
        issueDate: inv.issue_date || inv.issueDate,
        dueDate: inv.due_on || inv.dueDate,
        customer: {
          name: inv.customer_name || (inv.customer && inv.customer.name) || "",
          address: inv.customer_address || (inv.customer && inv.customer.address) || "",
          email: inv.customer_email || "",
          phone: inv.customer_phone || ""
        },
        items: normalizeItems(inv.items),
        subtotal: inv.subtotal,
        tax: inv.tax,
        total: inv.total,
        amountPaid: inv.amount_paid != null ? inv.amount_paid : inv.amountPaid,
        balanceDue: (Number(inv.total) || 0) - (Number(inv.amount_paid != null ? inv.amount_paid : inv.amountPaid) || 0),
        paymentMethod: inv.payment_method || inv.paymentMethod || "",
        note: inv.note || ""
      };
    } else if (docType === "receipt") {
      var r = source || sampleReceipt(currency);
      base.receipt = r;
      base.invoice = {
        customer: { name: r.payer || r.customerName || "" },
        paymentMethod: r.paymentMethod || "",
        note: r.note || "",
        total: r.amount
      };
    } else if (docType === "payslip") {
      var p = source || samplePayslip(currency);
      base.employee = p.employee;
      base.payroll = p.payroll;
    } else if (docType === "financial_report" || docType === "employee_report") {
      var rep = source || sampleReport(docType);
      base.report = rep;
    } else if (docType === "ticket") {
      base.ticket = normalizeTicket(source || sampleTicket());
    } else if (docType === "agreement") {
      base.agreement = source || { title: "Sample agreement", party: "Counterparty", body: "<p>Agreement text goes here.</p>" };
    }
    return base;
  }

  function normalizeItems(items) {
    if (!Array.isArray(items)) return [];
    return items.map(function (it) {
      if (typeof it === "string") return { description: it, qty: 1, unit: 0, tax: 0, total: 0 };
      return {
        description: it.description || it.name || "Item",
        qty: Number(it.qty != null ? it.qty : it.quantity) || 1,
        // Cursor 2026-10-24: DB invoice lines use unit_price; layouts use unit.
        unit: Number(it.unit != null ? it.unit : it.unit_price) || 0,
        tax: Number(it.tax) || 0,
        total: Number(it.total != null ? it.total : it.line_total) || 0
      };
    });
  }

